"""
Суррогатные BIGSERIAL PK в сырых таблицах источников.

Нужны, чтобы в person_evidence писать числа (forum_flight_id, …),
а не составные строки. Вызывается при каждой сборке; колонка
добавляется только если её ещё нет.
"""

from __future__ import annotations

import asyncpg

from analysis.person.sources import ROW_ID_COLUMNS
from analysis.person.util import log


async def ensure_public_row_ids(conn: asyncpg.Connection) -> None:
    """
    Гарантирует числовой PK строки в forum/skyteam/pointz таблицах.

    Имя функции историческое («public»); сейчас таблицы уже в схемах источников.
    В лог пишется «уже есть» / «добавили» по каждой колонке.
    """
    log("0b) Суррогатные PK строк источников…")
    already = 0
    added = 0
    for schema, table, col in ROW_ID_COLUMNS:
        exists = await conn.fetchval(
            """
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = $1
              AND table_name = $2
              AND column_name = $3
            """,
            schema,
            table,
            col,
        )
        if exists:
            log(f"   уже есть: {schema}.{table}.{col}")
            already += 1
            continue
        log(f"   добавили: {schema}.{table}.{col} (ALTER PRIMARY KEY — может занять время)")
        await conn.execute(
            f"""
            ALTER TABLE {schema}.{table}
              ADD COLUMN {col} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
            """
        )
        added += 1
    log(f"   PK строк: уже было {already}, добавлено {added}")
